-- Run this in Supabase SQL Editor for the GAMGAM project.
create table if not exists public.gamgam_transactions (
  id bigint generated by default as identity primary key,
  wallet text not null,
  tx_hash text not null unique,
  operation_id text,
  kind text not null check (kind in ('swap', 'bridge')),
  from_chain_id bigint not null,
  to_chain_id bigint not null,
  from_chain text not null,
  to_chain text not null,
  from_token text,
  to_token text,
  amount text,
  relay_request_id text,
  status text not null default 'submitted',
  created_at timestamptz not null default now()
);

create index if not exists gamgam_transactions_created_at_idx
  on public.gamgam_transactions (created_at desc);
create index if not exists gamgam_transactions_wallet_idx
  on public.gamgam_transactions (lower(wallet));
create index if not exists gamgam_transactions_operation_idx
  on public.gamgam_transactions (operation_id);

alter table public.gamgam_transactions enable row level security;
-- Intentionally create no anon/authenticated table policies.
-- All reads/writes go through Next.js server routes using SUPABASE_SERVICE_ROLE_KEY.
